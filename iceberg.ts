export const levels = levelDefinitions.map((level) => {
  const items = cards.filter((card) => card.level === level.id);
  return { ...level, cards: items, first: items[0].id, last: items[items.length - 1].id };
});

export const numberLabel = (id: number) => String(id).padStart(2, '0');
export const levelLabel = (id: LevelId) => levels[id].label;
export const chapterHeading = (id: LevelId) => levels[id].heading;
export const chapterRange = (id: LevelId) => {
  const chapter = levels[id];
  return chapter.first === chapter.last ? numberLabel(chapter.first) : `${numberLabel(chapter.first)}–${numberLabel(chapter.last)}`;
};
export const adjacentIndex = (index: number, delta: number) => Math.max(0, Math.min(cards.length - 1, index + delta));

const normalize = (value: string) => value.normalize('NFKC').toLocaleLowerCase('uk').replace(/['’‘ʼ`]/g, '').trim();

// Build the search index once, not on every keystroke or camera update.
const searchIndex = cards.map((card) => normalize(`${card.id} ${chapterHeading(card.level)} ${levelLabel(card.level)} рівень ${card.level} ${card.name} ${card.title} ${card.narration} ${card.alternateTitle}`));

export function searchCards(query: string, level: LevelId | 'all' = 'all'): readonly IcebergCard[] {
  const scope = level === 'all' ? cards : levels[level].cards;
  const value = normalize(query);
  if (!value) return scope;
  const chapter = value.match(/^(?:глава|рівень)\s*([0-6])$/);
  if (chapter) return scope.filter((card) => card.level === Number(chapter[1]));

  // NFKC normalizes the numero sign (№) to "No".
  const number = value.match(/^(?:№|#|no)?\s*(\d+)$/);
  if (number && cards.some((card) => card.id === Number(number[1]))) {
    return scope.filter((card) => card.id === Number(number[1]));
  }

  const terms = value.split(/\s+/);
  return scope.filter((card) => {
    const text = searchIndex[card.id - 1];
    return terms.every((term) => text.includes(term));
  });
}

export function planCsv(): string {
  const header = ['Рівень айсберга', 'Звичайна назва', 'Назва для фото', '№ картки у відео', 'Текст для начитки', 'Запасна назва з попереднього плану'];
  const values = cards.map((card) => [
    card.level === 0 ? 'Пролог' : card.level, card.name, card.title, card.id, card.narration, card.alternateTitle,
  ]);
  return [header, ...values].map((row) => row.map((value) => `"${String(value).replace(/"/g, '""')}"`).join(',')).join('\r\n');
}